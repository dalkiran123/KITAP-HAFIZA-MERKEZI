// Read-only regression checks for the single-page application.
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const html=readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(Boolean);
assert.ok(scripts.length>0,'Inline scripts should exist');
for(const [i,code] of scripts.entries())new vm.Script(code,{filename:'index.html:inline-'+i});
const videoHtml=readFileSync('documentaries.html','utf8');
const videoScripts=videoHtml.split('<script>').slice(1).map(part=>part.split('</script>')[0]).filter(Boolean);
assert.ok(videoScripts.length>0,'Video page inline script should exist');
for(const [i,code] of videoScripts.entries())new vm.Script(code,{filename:'documentaries.html:inline-'+i});
for(const file of ['catalog.js','catalog-queue.js'])new vm.Script(readFileSync(file,'utf8'),{filename:file});
assert.match(html,/catalog-added/,'Catalog addition timestamp missing');
assert.match(html,/catalog\.slice\(\)\.sort/,'Ready-first sorting missing');
assert.match(html,/kitap-hafiza-current-reading-v1/,'Recommendation rotation missing');
assert.match(html,/localStorage\.getItem\(key\)/,'Existing local book data key must be retained');
console.log('PASS: JS syntax and catalog/recommendation regression checks');

const presence=readFileSync('assets/inline-friend-presence.js','utf8');
new vm.Script(presence,{filename:'assets/inline-friend-presence.js'});
assert.match(html,/assets\/inline-friend-presence\.js/,'Main screen must load inline presence');
assert.match(html,/nav\.v2nav button \.bc-friends[\s\S]*?display:none !important/,'Navigation must hide avatar overlays even with cached JS');
assert.doesNotMatch(html,/friends-presence-preview\.js/,'Old floating friends preview must not load');
assert.doesNotMatch(html,/BİRLİKTE · Arkadaşlarla aynı ekranda \(Test\)/,'Separate Together test link must not appear');
assert.match(presence,/bookcenter_arena_botworld_v1/,'Presence must read existing Arena simulation data');
assert.match(presence,/reading\[0\]/,'Presence must read persisted bot book history');
assert.match(presence,/simulated:true,localSimulation:true,online:false/,'Local bot history must not claim online status');
assert.match(presence,/BOOKCENTER_PRESENCE_API_URL/,'Remote presence must be opt-in configured');
assert.match(presence,/if\(menu\)\s*\{[\s\S]*?root\.append\(chip\);return;/,'Menu presence must use a compact badge, not overlapping avatars');
assert.match(presence,/bc-book-activity/,'Book cards must show simulated reading activity label');
assert.match(presence,/type==='book'/,'Activity labels must be restricted to book cards');
console.log('PASS: inline friend presence integration checks');
